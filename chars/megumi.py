class _Meg:
    def __init__(self): self.H0 = make_head(); self.L = None

    def pose(self, cx, cy, s, yaw=0., pitch=0., roll=0., persp=.10): return make_head().pose(cx, cy, s, yaw, pitch, roll, persp)

    def _hair(self, H, f, wind):
        L = locks(H)
        for l in L:
            ph = (l.id * .618) % 1; off = wind_off(H, wind, f, ph, {'fr': .55, 'side': .7}.get(l.tag, 1.))
            l.build(H, off)
        return L

    def back(self, cel, H, light='day', f=0, wind=(0, 0), seed=0, L=None):
        w = lw(H.s); pal = HAIR[light]; LT = LIGHT[light]
        bk = sorted([l for l in (L or self._hair(H, f, wind)) if self._isback(l)], key=lambda l: l.depth)
        hair_group(cel, bk, dict(pal, base=pal['sh'], hi=None), *w, seed=seed, key=LT['key'], caps=[scalp(H, lambda t: -.42, 1.06, front=False)], shade=False)

    @staticmethod
    def _isback(l): return l.tag != 'fr' and (l.vis < -.22 or l.depth < -.34)

    def head(self, cel, H, expr='deadpan', light='day', f=0, wind=(0, 0), seed=0, parts='bnf', L=None, **ex):
        """parts: b back hair, n neck, f face + front hair"""
        E = dict(EXPR[expr]) if isinstance(expr, str) else dict(expr); E.update(ex)
        LT = LIGHT[light]; w = lw(H.s); pal = HAIR[light]; L = L or self._hair(H, f, wind)
        if 'b' in parts: self.back(cel, H, light, f, wind, seed, L)
        if 'n' in parts: neck(cel, H, LT, w, .335, seed=seed)
        if 'f' not in parts: return cel
        if H.pitch > .05: cel.fill(H.under(), LT['skin2'])
        for s in (-1, 1): ear(cel, H, s, LT, w, seed)
        F = H.face(); cel.fill(F, LT['skin'])
        (mn.lit_plane if LT.get('lit') else face_shadow)(cel, H, LT, F)
        # fringe cast shadow on the skin
        fr = sorted([l for l in L if not self._isback(l)], key=lambda l: l.depth)
        kx, ky = LT['key']; off = np.array([-kx * .085, .115]) * H.s
        cel.clip(F)
        for l in fr:
            if l.tag in ('fr', 'side'): cel.fill(l.poly + off, LT['skin2'])
        cel.unclip()
        planes(cel, H, C, E, LT, F)
        for s in (-1, 1):
            far = s * H.yaw > .3
            if far: cel.clip(F)
            eye(cel, H, s, C, E, LT, w, seed)
            if far: cel.unclip()
        nose(cel, H, C, LT, w, seed); mouth(cel, H, E['mouth'], LT, w, seed)
        for s in (-1, 1): brow(cel, H, s, C, E, LT, w, seed)
        if H.yaw * H.yaw > .75 ** 2: cel.fill(H.P3(H.nose_profile()), LT['skin'])
        face_line(cel, H, F, w, LT['line'], seed + 2)
        hair_group(cel, fr, pal, *w, seed=seed, key=LT['key'], caps=[scalp(H, hl, 1.05)])
        return cel

    def bust(self, cx, cy, s, yaw=0., pitch=0., roll=0., expr='deadpan', light='day', f=0, wind=(0, 0), seed=0, torso=None, w=1920, h=1080, finish=True, under=None, over=None, **ex):
        """head at (cx, cy), s px per head unit -> premultiplied layer with airbrush and rim.  torso = dict(yaw, pitch, roll, drop) overrides"""
        cel = Cel(w, h); H = self.pose(cx, cy, s, yaw, pitch, roll); LT = LIGHT[light]; W_ = lw(s)
        T = mn.torso_under(H, **(torso or {})); L = self._hair(H, f, wind)
        self.back(cel, H, light, f, wind, seed, L)
        mn.uniform(cel, T, BODY, LT, W_, seed, 'back'); neck(cel, H, LT, W_, .335, seed=seed)
        if under: under(cel, H, T)
        mn.uniform(cel, T, BODY, LT, W_, seed, 'front')
        self.head(cel, H, expr, light, f, wind, seed, parts='f', L=L, **ex)
        if over: over(cel, H, T)
        lay = cel.layer(h, w)
        return mn.grade(lay, LT, (cx - 1.9 * s, cy - 1.6 * s, cx + 1.9 * s, cy + 3 * s), max(.5, s / 200)) if finish else lay




